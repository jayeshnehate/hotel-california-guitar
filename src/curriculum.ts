export interface ChordShape {
  name: string;
  strings: number[]; // 6 strings from low E (index 0) to high e (index 5). -1 = muted (X), 0 = open (O), 1..12 = fret
  fingers: (number | null)[]; // 1=Index, 2=Middle, 3=Ring, 4=Pinky, 0=None, null=muted/open
  barre?: {
    fret: number;
    fromString: number; // 0=low E, 5=high e
    toString: number;
    finger: number;
  };
  baseFret?: number; // default 1
}

export type StrumBeat = 'D' | 'U' | 'G' | '-'; // Down, Up, Ghost/mute, Rest

export interface ArpeggioStep {
  stringIndex: number; // 0=low E, 5=high e
  fret: number;
  finger?: number;
}

export interface CurriculumNode {
  id: string; // "01" - "50"
  phase: number; // 1 - 5
  type: 'chord-pair' | 'strumming' | 'technique' | 'barre' | 'loop' | 'arpeggio' | 'song';
  chords: ChordShape[];
  anchorFinger?: number; // 1, 2, 3, or 4
  anchorString?: number; // 0-5
  anchorFret?: number;
  targetBpm: number;
  targetReps: number;
  strumPattern?: StrumBeat[];
  arpeggioPattern?: ArpeggioStep[];
  isBossGate?: boolean;
}

